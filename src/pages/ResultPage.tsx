import { useParams, Link } from 'react-router-dom';
import { ArrowRight, Sparkles, Loader2, Download } from 'lucide-react';
import { useEffect, useState } from 'react';
import { doc, getDoc } from 'firebase/firestore';
import { db } from '../lib/firebase';

export default function ResultPage() {
  const { id } = useParams();
  const [svgData, setSvgData] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(false);

  useEffect(() => {
    if (id) {
      fetchTrace();
    }
  }, [id]);

  const fetchTrace = async () => {
    try {
      const docRef = doc(db, 'shared_traces', id as string);
      const docSnap = await getDoc(docRef);
      if (docSnap.exists()) {
        setSvgData(docSnap.data().svg);
      } else {
        setError(true);
      }
    } catch (err) {
      console.error(err);
      setError(true);
    } finally {
      setLoading(false);
    }
  };

  const handleDownload = () => {
    if (!svgData) return;
    const blob = new Blob([svgData], { type: 'image/svg+xml' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `tracemagic-shared-${id}.svg`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  if (loading) {
    return (
      <div className="py-32 flex-grow flex flex-col items-center justify-center">
        <Loader2 className="w-8 h-8 animate-spin text-[#C1FF00] mb-6" />
        <p className="text-[11px] font-bold text-white/40 uppercase tracking-widest">Loading vector data...</p>
      </div>
    );
  }

  if (error || !svgData) {
    return (
      <div className="py-32 flex-grow flex flex-col items-center justify-center text-center px-4">
        <h1 className="text-4xl font-black uppercase tracking-tight text-white mb-4">Trace Not Found</h1>
        <p className="text-white/60 mb-8 font-medium">This shared trace may have been deleted or never existed.</p>
        <Link to="/app" className="bg-[#111] border border-white/10 text-white px-6 py-3 rounded-xl font-bold text-sm uppercase tracking-widest hover:bg-white/5 transition-colors">Create your own</Link>
      </div>
    );
  }

  return (
    <div className="py-24 flex-grow flex flex-col items-center justify-center text-center px-4">
      <div className="bg-[#111] p-10 md:p-16 rounded-3xl border border-white/10 shadow-[0_40px_100px_rgba(0,0,0,0.5)] max-w-4xl w-full">
        <div className="flex flex-col md:flex-row items-center justify-between gap-8 mb-10">
          <div className="flex items-center gap-6 text-left">
            <div className="bg-[#C1FF00] w-14 h-14 rounded-xl flex items-center justify-center text-black">
              <Sparkles className="w-6 h-6" />
            </div>
            <div>
              <h1 className="text-3xl font-black uppercase tracking-tight text-white">Reconstructed Vector</h1>
              <p className="text-[10px] font-bold text-[#C1FF00] uppercase tracking-widest mt-1">Generated by TraceMagic</p>
            </div>
          </div>
          <button 
            onClick={handleDownload}
            className="flex items-center gap-3 bg-white/10 hover:bg-white/20 text-white px-6 py-3.5 rounded-xl text-xs font-bold uppercase tracking-widest transition-colors"
          >
            <Download className="w-5 h-5" /> Download SVG
          </button>
        </div>
        
        <div className="bg-black rounded-2xl aspect-square md:aspect-video border border-white/10 flex items-center justify-center mb-12 overflow-hidden p-8 relative">
          <div className="absolute inset-0 opacity-[0.03] bg-[url('data:image/svg+xml;base64,PHN2ZyB4bWxucz0iaHR0cDovL3d3dy53My5vcmcvMjAwMC9zdmciIHdpZHRoPSIyMCIgaGVpZ2h0PSIyMCI+CjxyZWN0IHdpZHRoPSIxMCIgaGVpZ2h0PSIxMCIgZmlsbD0iI2Y4ZmFmYyIvPgo8cmVjdCB4PSIxMCIgd2lkdGg9IjEwIiBoZWlnaHQ9IjEwIiBmaWxsPSIjZjFmMjY2Ii8+CjxyZWN0IHk9IjEwIiB3aWR0aD0iMTAiIGhlaWdodD0iMTAiIGZpbGw9IiNmMWYyZjYiLz4KPHJlY3QgeD0iMTAiIHk9IjEwIiB3aWR0aD0iMTAiIGhlaWdodD0iMTAiIGZpbGw9IiNmOGZhZmMiLz4KPC9zdmc+')] [background-size:20px_20px]" />
          <div className="w-full h-full flex items-center justify-center z-10 [&>svg]:max-w-full [&>svg]:max-h-full" dangerouslySetInnerHTML={{ __html: svgData }} />
        </div>

        <div className="pt-10 border-t border-white/10">
          <h2 className="text-2xl font-black text-white uppercase tracking-tight mb-6">Build your own vectors in seconds.</h2>
          <Link to="/app" className="bg-[#C1FF00] text-black px-10 py-5 rounded-xl font-black text-sm uppercase tracking-widest hover:bg-[#a6db00] transition-colors inline-flex items-center gap-3 w-full md:w-auto justify-center">
            Initialize Engine <ArrowRight className="w-5 h-5" />
          </Link>
        </div>
      </div>
    </div>
  );
}
